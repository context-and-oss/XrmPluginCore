using System.Collections.Generic;
using System.Linq;
using System.Text;
using XrmPluginCore.SourceGenerator.Models;
using static XrmPluginCore.SourceGenerator.CodeGeneration.Indent;

namespace XrmPluginCore.SourceGenerator.CodeGeneration;

/// <summary>
/// Generates wrapper class source code for plugin step registrations
/// </summary>
internal static class WrapperClassGenerator
{
	/// <summary>
	/// Generates a complete source file containing wrapper classes for a plugin step registration.
	/// Generates PreImage and PostImage wrappers, and ActionWrapper for the new method reference API.
	/// </summary>
	public static string GenerateWrapperClasses(PluginStepMetadata metadata)
	{
		var imagesWithAttributes = metadata.Images.Where(i => i.Attributes.Any()).ToList();

		// Estimate capacity: ~500 chars per image wrapper class + ~300 for ActionWrapper
		var estimatedCapacity = (imagesWithAttributes.Count * 500) + 500;
		var sb = new StringBuilder(estimatedCapacity);

		// File header and using directives
		sb.Append(GetFileHeader(metadata.NullableAnnotationsEnabled));

		// Generated types live in the plugin's own namespace with registration-derived names, so no
		// per-registration namespace (and no aliased-usings juggling) is needed.
		var namespaceToUse = metadata.Namespace;

		// Namespace declaration
		sb.AppendLine($"namespace {namespaceToUse}");
		sb.AppendLine("{");

		// Generate Image wrapper classes if we have images with attributes
		foreach (var image in imagesWithAttributes)
		{
			GenerateImageWrapperClass(sb, metadata, image);
		}

		GenerateActionWrapperClass(sb, metadata, imagesWithAttributes);

		// Close namespace
		sb.AppendLine("}");

		return sb.ToString();
	}

	/// <summary>
	/// Generates an Image wrapper class (PreImage or PostImage)
	/// </summary>
	private static void GenerateImageWrapperClass(StringBuilder sb, PluginStepMetadata metadata, ImageMetadata image)
	{
		var className = metadata.ImageClassName(image.ImageType);

		// Class header with documentation, attribute, field, and constructor
		sb.Append(GetImageClassHeader(
			className,
			metadata.EntityTypeName,
			metadata.EntityTypeFullName,
			metadata.EventOperation,
			metadata.ExecutionStage,
			image.ImageType));

		// Generate properties for each image attribute.
		// Skip attributes that map to "Id"/"LogicalName" - they are always exposed via the synthetic
		// IPluginImage members (forwarding to the Entity base type).
		foreach (var attr in image.Attributes)
		{
			if (attr.PropertyName == "Id" || attr.PropertyName == "LogicalName")
			{
				continue;
			}

			sb.Append(GetPropertyTemplate(attr));
		}

		// Close class
		sb.Append(L1).Append("}");
	}

	/// <summary>
	/// Generates the ActionWrapper class that wraps the service method call.
	/// This is used by the runtime to discover and invoke the plugin action.
	/// </summary>
	private static void GenerateActionWrapperClass(StringBuilder sb, PluginStepMetadata metadata, List<ImageMetadata> images)
	{
		var hasPreImage = images.Any(i => i.ImageType == Constants.PreImageTypeName);
		var hasPostImage = images.Any(i => i.ImageType == Constants.PostImageTypeName);

		// ActionWrapper header with documentation, class declaration, and service retrieval
		sb.Append(GetActionWrapperHeader(
			metadata.ActionWrapperClassName,
			metadata.ServiceTypeName,
			metadata.HandlerMethodName,
			metadata.ServiceTypeFullName));

		// Get context if images are needed
		if (hasPreImage || hasPostImage)
		{
			sb.AppendLine();
			sb.AppendLine($"{L4}var context = serviceProvider.GetRequiredService<IPluginExecutionContext>();");
		}

		var args = new List<string>();
		if (hasPreImage)
		{
			sb.AppendLine();
			sb.Append(GetPreImageRetrieval(metadata.ImageClassName(Constants.PreImageTypeName)));
			args.Add("preImage");
		}
		if (hasPostImage)
		{
			sb.AppendLine();
			sb.Append(GetPostImageRetrieval(metadata.ImageClassName(Constants.PostImageTypeName)));
			args.Add("postImage");
		}

		var argsString = string.Join(", ", args);

		// ActionWrapper footer with method invocation and closing braces
		sb.AppendLine();
		sb.Append(GetActionWrapperFooter(metadata.HandlerMethodName, argsString));
	}

	/// <summary>
	/// Generates a unique hint name for the source file
	/// </summary>
	public static string GenerateHintName(PluginStepMetadata metadata)
	{
		// UniqueId already contains PluginClassName, so no need to duplicate
		return $"{metadata.UniqueId}.g.cs";
	}

	#region Template Methods

	private static string GetFileHeader(bool nullableEnabled) =>
$"""
// <auto-generated />
{Helpers.NullableHelper.FileDirective(nullableEnabled)}
using System;
using System.Linq;
using System.Runtime.CompilerServices;
using Microsoft.Xrm.Sdk;
using Microsoft.Extensions.DependencyInjection;
using XrmPluginCore;

""";

	private static string GetImageClassHeader(
		string className,
		string entityTypeName,
		string entityTypeFullName,
		string eventOperation,
		string executionStage,
		string imageType)
	{
		var interfaceName = imageType == Constants.PostImageTypeName
			? Constants.PostImageInterfaceName
			: Constants.PreImageInterfaceName;

		return
			$"{L1}/// <summary>\n" +
			$"{L1}/// Type-safe wrapper for {entityTypeName} {eventOperation} {executionStage} {imageType}\n" +
			$"{L1}/// </summary>\n" +
			$"{L1}[CompilerGenerated]\n" +
			$"{L1}public sealed class {className} : {interfaceName}<{entityTypeFullName}>\n" +
			$"{L1}{{\n" +
			$"{L2}public {className}(Entity entity)\n" +
			$"{L2}{{\n" +
			$"{L3}Entity = entity.ToEntity<{entityTypeFullName}>();\n" +
			$"{L2}}}\n\n" +
			$"{L2}public {entityTypeFullName} Entity {{ get; }}\n\n" +
			$"{L2}Microsoft.Xrm.Sdk.Entity IPluginImage.Entity => this.Entity;\n\n" +
			$"{L2}/// <summary>\n" +
			$"{L2}/// The unique identifier (primary key) of the record the image was captured for.\n" +
			$"{L2}/// </summary>\n" +
			$"{L2}public System.Guid Id => Entity.Id;\n\n" +
			$"{L2}/// <summary>\n" +
			$"{L2}/// The logical name of the entity captured in the image.\n" +
			$"{L2}/// </summary>\n" +
			$"{L2}public string LogicalName => Entity.LogicalName;\n\n";
	}

	private static string GetPropertyTemplate(Models.AttributeMetadata attr)
	{
		var sb = new StringBuilder();

		if (!string.IsNullOrWhiteSpace(attr.XmlDocumentation))
		{
			sb.Append(attr.XmlDocumentation).Append('\n');
		}

		// Mirror the underlying property's [Obsolete] so the deprecation warning surfaces in the
		// calling code rather than inside this auto-generated accessor. Marking the wrapper member
		// obsolete also suppresses CS0612/CS0618 for the Entity.{Property} access in its body, since
		// references to obsolete members from within an obsolete member are not reported.
		if (attr.IsObsolete)
		{
			sb.Append(GetObsoleteAttribute(attr));
		}

		sb.Append($"{L2}public {attr.TypeName} {attr.PropertyName} => Entity.{attr.PropertyName};\n\n");

		return sb.ToString();
	}

	/// <summary>
	/// Builds an [Obsolete] attribute line mirroring the underlying property's obsolete metadata.
	/// </summary>
	private static string GetObsoleteAttribute(Models.AttributeMetadata attr)
	{
		if (attr.ObsoleteMessage == null)
		{
			return $"{L2}[System.Obsolete]\n";
		}

		var messageLiteral = Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(attr.ObsoleteMessage, quote: true);

		return attr.ObsoleteIsError
			? $"{L2}[System.Obsolete({messageLiteral}, true)]\n"
			: $"{L2}[System.Obsolete({messageLiteral})]\n";
	}

	private static string GetActionWrapperHeader(string actionWrapperClassName, string serviceTypeName, string methodName, string serviceFullName) =>
		$"{L1}/// <summary>\n" +
		$"{L1}/// Generated action wrapper for {serviceTypeName}.{methodName}\n" +
		$"{L1}/// </summary>\n" +
		$"{L1}[CompilerGenerated]\n" +
		$"{L1}internal sealed class {actionWrapperClassName} : IActionWrapper\n" +
		$"{L1}{{\n" +
		$"{L2}/// <summary>\n" +
		$"{L2}/// Creates the action delegate that invokes the service method with appropriate images.\n" +
		$"{L2}/// </summary>\n" +
		$"{L2}public Action<IExtendedServiceProvider> CreateAction()\n" +
		$"{L2}{{\n" +
		$"{L3}return serviceProvider =>\n" +
		$"{L3}{{\n" +
		$"{L4}var service = serviceProvider.GetRequiredService<{serviceFullName}>();";

	private static string GetPreImageRetrieval(string preImageClassName) =>
		$"{L4}var preImageEntity = context?.PreEntityImages?.Values?.FirstOrDefault();\n" +
		$"{L4}var preImage = preImageEntity != null ? new {preImageClassName}(preImageEntity) : null;";

	private static string GetPostImageRetrieval(string postImageClassName) =>
		$"{L4}var postImageEntity = context?.PostEntityImages?.Values?.FirstOrDefault();\n" +
		$"{L4}var postImage = postImageEntity != null ? new {postImageClassName}(postImageEntity) : null;";

	private static string GetActionWrapperFooter(string methodName, string argsString) =>
		$"{L4}service.{methodName}({argsString});\n" +
		$"{L3}}};\n" +
		$"{L2}}}\n" +
		$"{L1}}}\n\n";

	#endregion
}
